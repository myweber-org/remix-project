interface UserPreferences {
  theme: 'light' | 'dark' | 'auto';
  language: string;
  notifications: boolean;
  fontSize: number;
  autoSave: boolean;
}

class UserPreferencesManager {
  private static readonly STORAGE_KEY = 'user_preferences';
  private static readonly DEFAULT_PREFS: UserPreferences = {
    theme: 'auto',
    language: 'en-US',
    notifications: true,
    fontSize: 14,
    autoSave: true
  };

  private preferences: UserPreferences;

  constructor() {
    this.preferences = this.loadPreferences();
  }

  private loadPreferences(): UserPreferences {
    try {
      const stored = localStorage.getItem(UserPreferencesManager.STORAGE_KEY);
      if (stored) {
        const parsed = JSON.parse(stored);
        return this.validatePreferences(parsed);
      }
    } catch (error) {
      console.warn('Failed to load preferences from storage:', error);
    }
    return { ...UserPreferencesManager.DEFAULT_PREFS };
  }

  private validatePreferences(data: unknown): UserPreferences {
    const prefs = { ...UserPreferencesManager.DEFAULT_PREFS };
    
    if (data && typeof data === 'object') {
      const obj = data as Record<string, unknown>;
      
      if (obj.theme === 'light' || obj.theme === 'dark' || obj.theme === 'auto') {
        prefs.theme = obj.theme;
      }
      
      if (typeof obj.language === 'string') {
        prefs.language = obj.language;
      }
      
      if (typeof obj.notifications === 'boolean') {
        prefs.notifications = obj.notifications;
      }
      
      if (typeof obj.fontSize === 'number' && obj.fontSize >= 8 && obj.fontSize <= 32) {
        prefs.fontSize = obj.fontSize;
      }
      
      if (typeof obj.autoSave === 'boolean') {
        prefs.autoSave = obj.autoSave;
      }
    }
    
    return prefs;
  }

  public getPreferences(): UserPreferences {
    return { ...this.preferences };
  }

  public updatePreferences(updates: Partial<UserPreferences>): boolean {
    const newPreferences = { ...this.preferences };
    let hasChanges = false;

    if (updates.theme !== undefined && ['light', 'dark', 'auto'].includes(updates.theme)) {
      newPreferences.theme = updates.theme;
      hasChanges = true;
    }

    if (updates.language !== undefined && typeof updates.language === 'string') {
      newPreferences.language = updates.language;
      hasChanges = true;
    }

    if (updates.notifications !== undefined && typeof updates.notifications === 'boolean') {
      newPreferences.notifications = updates.notifications;
      hasChanges = true;
    }

    if (updates.fontSize !== undefined && 
        typeof updates.fontSize === 'number' && 
        updates.fontSize >= 8 && 
        updates.fontSize <= 32) {
      newPreferences.fontSize = updates.fontSize;
      hasChanges = true;
    }

    if (updates.autoSave !== undefined && typeof updates.autoSave === 'boolean') {
      newPreferences.autoSave = updates.autoSave;
      hasChanges = true;
    }

    if (hasChanges) {
      this.preferences = newPreferences;
      this.savePreferences();
    }

    return hasChanges;
  }

  private savePreferences(): void {
    try {
      localStorage.setItem(
        UserPreferencesManager.STORAGE_KEY, 
        JSON.stringify(this.preferences)
      );
    } catch (error) {
      console.error('Failed to save preferences:', error);
    }
  }

  public resetToDefaults(): void {
    this.preferences = { ...UserPreferencesManager.DEFAULT_PREFS };
    this.savePreferences();
  }

  public exportPreferences(): string {
    return JSON.stringify(this.preferences, null, 2);
  }

  public importPreferences(jsonString: string): boolean {
    try {
      const parsed = JSON.parse(jsonString);
      const validated = this.validatePreferences(parsed);
      this.preferences = validated;
      this.savePreferences();
      return true;
    } catch (error) {
      console.error('Failed to import preferences:', error);
      return false;
    }
  }
}

